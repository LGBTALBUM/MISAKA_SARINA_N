const resolveBrandRefactorLocale = () => {
  const stored = localStorage.getItem('msarina.locale') || 'system';
  if (stored !== 'system' && BRAND_REFACTOR_LOCALES.includes(stored)) return stored;
  const browser = navigator.language || 'en';
  if (browser.toLowerCase().startsWith('ja')) return 'ja';
  if (browser.toLowerCase().startsWith('zh')) return 'zh-TW';
  if (browser.toLowerCase().startsWith('ca')) return 'ca';
  return 'en';
};

const applyBrandRefactorI18n = () => {
  const locale = resolveBrandRefactorLocale();
  const dict = brandRefactorTranslations[locale] || brandRefactorTranslations.en;
  document.querySelectorAll('[data-i18n^="brand"]').forEach((node) => {
    const key = node.getAttribute('data-i18n');
    const value = dict[key] || brandRefactorTranslations.en[key];
    if (value) node.textContent = value;
  });
};

window.applyBrandRefactorI18n = applyBrandRefactorI18n;

document.addEventListener('DOMContentLoaded', () => {
  applyBrandRefactorI18n();
  document.querySelectorAll('[data-locale-select]').forEach((select) => {
    select.addEventListener('change', () => window.setTimeout(applyBrandRefactorI18n, 0));
  });
});

document.addEventListener('msarina:dynamic-content', applyBrandRefactorI18n);
